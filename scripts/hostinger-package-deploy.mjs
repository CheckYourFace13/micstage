/**
 * Package current HEAD for Hostinger hosting_deployJsApplication.
 * Pre-bakes deployCommit so archive builds (no .git) keep the correct SHA.
 *
 * Usage: node scripts/hostinger-package-deploy.mjs [out.tgz]
 */
import { execSync } from "node:child_process";
import { mkdirSync, rmSync, copyFileSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const out =
  process.argv[2] ||
  path.join(root, "tmp-micstage-redeploy.tgz");
const stage = path.join(root, "tmp-redeploy-stage");

execSync(`node scripts/write-deploy-commit.mjs`, { cwd: root, stdio: "inherit" });
const sha = execSync("git rev-parse --short HEAD", { cwd: root, encoding: "utf8" }).trim();

if (existsSync(stage)) rmSync(stage, { recursive: true, force: true });
mkdirSync(stage, { recursive: true });

execSync(`git archive --format=tar HEAD | tar -x -C "${stage}"`, {
  cwd: root,
  stdio: "inherit",
  shell: true,
});

mkdirSync(path.join(stage, "src", "generated"), { recursive: true });
copyFileSync(
  path.join(root, "src", "generated", "deployCommit.ts"),
  path.join(stage, "src", "generated", "deployCommit.ts"),
);

if (existsSync(out)) rmSync(out, { force: true });
execSync(`tar -czf "${out}" -C "${stage}" .`, { cwd: root, stdio: "inherit", shell: true });
rmSync(stage, { recursive: true, force: true });

// Restore empty stub in working tree (bake is for archive only).
execSync(
  `node -e "const fs=require('fs');fs.writeFileSync('src/generated/deployCommit.ts',\`/* AUTO-GENERATED by scripts/write-deploy-commit.mjs - do not edit by hand. */\\n/** Full Git SHA baked at build time (empty when unavailable). */\\nexport const DEPLOY_COMMIT_FULL = \\\"\\\" as string;\\n/** Short Git SHA for /api/health deployCommit. */\\nexport const DEPLOY_COMMIT_SHORT = \\\"\\\" as string;\\n\`);"`,
  { cwd: root, stdio: "inherit", shell: true },
);

console.log(JSON.stringify({ ok: true, archive: out, sha }, null, 2));
