/**
 * Bake the current Git SHA into a small module so /api/health can report
 * deployCommit without manually setting DEPLOY_GIT_SHA on Hostinger.
 *
 * Runs at the start of `npm run build` (including Hostinger git auto-deploys).
 * Prefer git HEAD; fall back to common CI env vars. Runtime DEPLOY_GIT_SHA is
 * only a last-resort override when the baked short SHA is empty.
 */
import { execSync } from "node:child_process";
import { mkdirSync, writeFileSync, readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outDir = path.join(root, "src", "generated");
const outFile = path.join(outDir, "deployCommit.ts");

function fromEnv(name) {
  const t = process.env[name]?.trim();
  if (t && /^[0-9a-f]{7,40}$/i.test(t)) return t.slice(0, 40).toLowerCase();
  return "";
}

function resolveSha() {
  // Prefer the checkout being built. Do NOT prefer DEPLOY_GIT_SHA first:
  // Hostinger may still have a stale value from manual releases.
  try {
    return execSync("git rev-parse HEAD", { cwd: root, encoding: "utf8" })
      .trim()
      .slice(0, 40)
      .toLowerCase();
  } catch {
    // no git binary or not a repo
  }

  try {
    const head = readFileSync(path.join(root, ".git", "HEAD"), "utf8").trim();
    if (/^[0-9a-f]{40}$/i.test(head)) return head.toLowerCase();
    const m = head.match(/^ref:\s*(.+)$/);
    if (m) {
      const ref = readFileSync(path.join(root, ".git", m[1]), "utf8").trim();
      if (/^[0-9a-f]{40}$/i.test(ref)) return ref.toLowerCase();
    }
  } catch {
    // archive deploy without .git
  }

  for (const name of ["GITHUB_SHA", "GIT_COMMIT", "COMMIT_SHA", "SOURCE_VERSION", "DEPLOY_GIT_SHA"]) {
    const v = fromEnv(name);
    if (v) return v;
  }
  return "";
}

const full = resolveSha();
const short = full ? full.slice(0, 7) : "";

mkdirSync(outDir, { recursive: true });
const body = `/* AUTO-GENERATED by scripts/write-deploy-commit.mjs - do not edit by hand. */
/** Full Git SHA baked at build time (empty when unavailable). */
export const DEPLOY_COMMIT_FULL = ${JSON.stringify(full)} as string;
/** Short Git SHA for /api/health deployCommit. */
export const DEPLOY_COMMIT_SHORT = ${JSON.stringify(short)} as string;
`;
writeFileSync(outFile, body, "utf8");
console.log(`[deploy-commit] wrote ${path.relative(root, outFile)} short=${short || "(none)"}`);
